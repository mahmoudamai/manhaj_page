def apply(path):
    s = path.read_text(encoding="utf-8")
    m = s.rindex("/* self-check")
    s = s[:m] + CSS.strip() + "\n\n" + s[m:]
    # side column (head + help card) and main column (list + bottom line)
    h = s.index('<header class="m4-faq__head')
    s = s[:h] + '<aside class="m4-faq__side">\n\n    ' + s[h:]
    h = s.index("</header>", h) + len("</header>")
    s = s[:h] + "\n" + HELP + "\n    </aside>\n\n    <div class=\"m4-faq__main\">" + s[h:]
    b = s.index('<div class="m4-faq__bottom')
    b = s.index("</div>", b) + len("</div>")
    s = s[:b] + "\n\n    </div>" + s[b:]
    a = s.index('<div class="m4-faq__list')
    a = s.index(">", a) + 1
    b = s.index('<div class="m4-faq__bottom')
    b = s.rindex("</div>", a, b)          # closes the list
    s = s[:a] + "\n" + "\n".join(item(q, x) for q, x in QA) + "\n    " + s[b:]
    path.write_text(s, encoding="utf-8")
    return len(s)
