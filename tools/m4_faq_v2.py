def item(q, a):
    return f"""      <article class="m4-faq__item">
        <button
          class="m4-faq__question"
          type="button"
          aria-expanded="false"
        >
          <span class="m4-faq__question-text">
            {q}
          </span>
          <span
            class="m4-faq__plus"
            aria-hidden="true"
          ></span>
        </button>
        <div class="m4-faq__answer">
          <div class="m4-faq__answer-inner">
            <div class="m4-faq__answer-content">
              {a}
            </div>
          </div>
        </div>
      </article>"""


def apply(path):
    s = path.read_text(encoding="utf-8")
    a = s.index('<div class="m4-faq__list')
    a = s.index(">", a) + 1
    b = s.index('<div class="m4-faq__bottom')
    b = s.rindex("</div>", a, b)          # closes the list
    s = s[:a] + "\n" + "\n".join(item(q, x) for q, x in QA) + "\n    " + s[b:]
    path.write_text(s, encoding="utf-8")
    return len(s)
